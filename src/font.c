static const uint8_t *glyph_for(char c) {
    if (c >= 'a' && c <= 'z') c -= 32;
    if (c < 0x20 || c > 0x7F) c = ' ';
    return font5x7[c - 0x20];
}

void gfx_text(int x, int y, const char *s, int scale, int color) {
    int cx = x;
    while (*s) {
        const uint8_t *g = glyph_for(*s);
        for (int r = 0; r < FONT_H; r++) {
            uint8_t row = g[r];
            for (int col = 0; col < FONT_W; col++) {
                if (row & (0x80 >> col)) {
                    gfx_fill_rect(cx + col * scale, y + r * scale, scale, scale, color);
                }
            }
        }
        cx += FONT_CELL_W * scale;
        s++;
    }
}

int gfx_text_width(const char *s, int scale) {
    int n = 0;
    while (*s++) n++;
    return n * FONT_CELL_W * scale;
}
